#!/usr/bin/env python3
"""Generate the Antimatter app icon from one geometry: an eclipse cut by a bar.

Redrawn as vectors from the original 1024 PNG (the source SVG was lost).

Writes
  design/app-icon/antimatter-icon.svg   flattened vector source (glow, disk, bar)
  antimatter/AppIcon.icon/              Icon Composer bundle for macOS 26 Liquid
                                        Glass: the disk and the bar are separate
                                        glass layers. Xcode 26 compiles it; the
                                        file-system synchronized group picks it
                                        up, and it shares the AppIcon name with
                                        the asset catalog set, which stays as the
                                        pre-Tahoe fallback.

Needs: pip install cairosvg
Run from the repo root: python3 design/app-icon/make-icon.py
"""
import json
import math
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent

# Geometry on the 1024 canvas, measured from the original icon.
DISK_C = (512.0, 512.0)
DISK_R = 165.0
BAR_W = 58.0                         # across
BAR_A = (206.0, 276.5)               # centre line ends, 45 degrees
BAR_B = (749.0, 820.0)

VIOLET = "#A77DFF"     # bar tips
INDIGO = "#1B0040"     # bar middle, over the disk
DISK = "#2A0050"
RIM = "#6A10B0"


def bar_points():
    (x0, y0), (x1, y1) = BAR_A, BAR_B
    dx, dy = x1 - x0, y1 - y0
    n = math.hypot(dx, dy)
    nx, ny = -dy / n * BAR_W / 2, dx / n * BAR_W / 2
    return [(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)]


def bar_d():
    p = bar_points()
    return "M " + " L ".join(f"{x:.2f} {y:.2f}" for x, y in p) + " Z"


def disk_d():
    cx, cy = DISK_C
    r = DISK_R
    return (f"M {cx - r:.2f} {cy:.2f} A {r} {r} 0 1 0 {cx + r:.2f} {cy:.2f} "
            f"A {r} {r} 0 1 0 {cx - r:.2f} {cy:.2f} Z")


def flat_svg():
    (x0, y0), (x1, y1) = BAR_A, BAR_B
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
<!-- Generated by make-icon.py; edit the script, not this file. -->
<defs>
<radialGradient id="glow" cx="512" cy="512" r="512" gradientUnits="userSpaceOnUse">
<stop offset="0" stop-color="#3A3A5C"/>
<stop offset="0.55" stop-color="#1E1E30"/>
<stop offset="1" stop-color="#000000"/>
</radialGradient>
<radialGradient id="disk" cx="512" cy="512" r="{DISK_R}" gradientUnits="userSpaceOnUse">
<stop offset="0.35" stop-color="#000000"/>
<stop offset="1" stop-color="{DISK}"/>
</radialGradient>
<linearGradient id="bar" x1="{x0}" y1="{y0}" x2="{x1}" y2="{y1}" gradientUnits="userSpaceOnUse">
<stop offset="0" stop-color="{VIOLET}"/>
<stop offset="0.3" stop-color="{INDIGO}"/>
<stop offset="0.7" stop-color="{INDIGO}"/>
<stop offset="1" stop-color="{VIOLET}"/>
</linearGradient>
</defs>
<rect width="1024" height="1024" fill="url(#glow)"/>
<path d="{disk_d()}" fill="url(#disk)" stroke="{RIM}" stroke-width="3"/>
<path d="{bar_d()}" fill="url(#bar)"/>
</svg>
'''


def rgba(h, a=1.0):
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
    return f"extended-srgb:{r:.5f},{g:.5f},{b:.5f},{a:.5f}"


def layer_svg(d):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
            f'  <path fill="#000000" d="{d}"/>\n</svg>\n')


def write_icon_bundle():
    root = REPO / "antimatter" / "AppIcon.icon"
    shutil.rmtree(root, ignore_errors=True)
    (root / "Assets").mkdir(parents=True)
    (root / "Assets" / "disk.svg").write_text(layer_svg(disk_d()))
    (root / "Assets" / "bar.svg").write_text(layer_svg(bar_d()))
    tinted = {"appearance": "tinted", "value": {"solid": rgba("#FFFFFF")}}
    doc = {
        "fill-specializations": [
            {"value": {"linear-gradient": [rgba("#3A3A5C"), rgba("#0A0A12")]}},
            {"appearance": "dark", "value": {"linear-gradient": [rgba("#2B2A44"), rgba("#050508")]}},
        ],
        "groups": [
            {
                "name": "Bar",
                "layers": [{
                    "name": "Bar", "image-name": "bar.svg", "glass": True,
                    "fill-specializations": [{"value": {"solid": rgba(VIOLET)}}, tinted],
                }],
                "lighting": "individual", "specular": True,
                "shadow": {"kind": "neutral", "opacity": 0.5},
                "translucency": {"enabled": True, "value": 0.3},
            },
            {
                "name": "Eclipse",
                "layers": [{
                    "name": "Disk", "image-name": "disk.svg", "glass": True,
                    "fill-specializations": [{"value": {"solid": rgba(DISK)}}, tinted],
                }],
                "lighting": "individual", "specular": True,
                "shadow": {"kind": "neutral", "opacity": 0.5},
                "translucency": {"enabled": True, "value": 0.2},
            },
        ],
        "supported-platforms": {"squares": ["macOS"]},
    }
    (root / "icon.json").write_text(json.dumps(doc, indent=2) + "\n")


def main():
    (HERE / "antimatter-icon.svg").write_text(flat_svg())
    write_icon_bundle()


if __name__ == "__main__":
    main()
